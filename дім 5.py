# Словник із користувачами та їх віковими групами (з доданими іменами)
users_dict = {
    "Матвій": "Підліток",
    "Деннис": "Підліток",
    "Іван": "Дорослий",
    "Олександр": "Підліток",
    "Марія": "Дорослий",
    "Максим": "Дитина",
    "Софія": "Підліток",
    "Катерина": "Дитина"
}


def find_user_age_group():
    print("Доступні користувачі у базі:", ", ".join(users_dict.keys()))
    name = input("\nВведіть ім'я користувача для пошуку: ").strip()

    try:
        # Намагаємося отримати значення за ключем.
        # Якщо імені немає у словнику, Python автоматично викине виняток KeyError.
        age_group = users_dict[name]

    except KeyError:
        # Обробка винятку, коли ключ не знайдено
        print(f"❌ Помилка: Користувача з ім'ям «{name}» не знайдено у словнику!")

    else:
        # Виконується, якщо виняток не виник
        print(f"✅ Знайдено! Користувач «{name}» належить до вікової групи: {age_group}")

    finally:
        print("Пошук завершено.")


if __name__ == "__main__":
    find_user_age_group()